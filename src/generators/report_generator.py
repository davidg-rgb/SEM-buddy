def export_keyword_xlsx(keyword_data: dict, output_path: str) -> str:
    """Export keyword data to XLSX with sheets per ad group.

    Includes columns: keyword, match_type, monthly_searches, avg_cpc_sek, competition.
    """
    import openpyxl
    from openpyxl.styles import Font, PatternFill

    wb = openpyxl.Workbook()
    # Remove default sheet
    wb.remove(wb.active)

    header_font = Font(bold=True)
    header_fill = PatternFill(start_color="4472C4", end_color="4472C4", fill_type="solid")
    header_text = Font(bold=True, color="FFFFFF")

    groups = keyword_data.get("groups", {})

    for group_name, keywords in groups.items():
        # Sanitize sheet name (max 31 chars, no special chars)
        sheet_name = group_name[:31].replace("/", "-").replace("\\", "-")
        ws = wb.create_sheet(title=sheet_name)

        # Headers
        headers = ["Sokord", "Matchningstyp", "Manadssokningar", "Snitt CPC (SEK)", "Konkurrens"]
        for col, header in enumerate(headers, 1):
            cell = ws.cell(row=1, column=col, value=header)
            cell.font = header_text
            cell.fill = header_fill

        # Data rows
        for row_idx, kw in enumerate(keywords, 2):
            if isinstance(kw, dict):
                ws.cell(row=row_idx, column=1, value=kw.get("text", ""))
                ws.cell(row=row_idx, column=2, value=kw.get("match_type", "PHRASE"))
                ws.cell(row=row_idx, column=3, value=kw.get("monthly_searches", ""))
                ws.cell(row=row_idx, column=4, value=kw.get("avg_cpc_sek", ""))
                ws.cell(row=row_idx, column=5, value=kw.get("competition", ""))
            elif isinstance(kw, str):
                ws.cell(row=row_idx, column=1, value=kw)

        # Auto-width columns
        for col in ws.columns:
            max_length = 0
            col_letter = col[0].column_letter
            for cell in col:
                if cell.value:
                    max_length = max(max_length, len(str(cell.value)))
            ws.column_dimensions[col_letter].width = min(max_length + 2, 40)

    if not groups:
        ws = wb.create_sheet(title="Inga sokord")
        ws.cell(row=1, column=1, value="Inga sokordsgrupper tillgangliga")

    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(out))

    logger.info("Exported keyword data to %s (%d sheets)", out, len(groups))
    return str(out)
