"""Structured diff engine comparing live Google Ads data against a CampaignPlan.

compare() produces a dict with seven diff categories.
format_audit_report() renders that dict as a Swedish-language markdown document.
"""

from __future__ import annotations

from datetime import datetime

from src.models.campaign import CampaignPlan


def compare(live_campaigns: list[dict], recommended_plan: CampaignPlan) -> dict:
    """Produce a structured diff between live and recommended campaigns.

    Campaign matching is done case-insensitively by campaign name.

    Args:
        live_campaigns: Enriched campaign dicts from fetch_live_campaigns().
        recommended_plan: CampaignPlan generated by the campaign build stage.

    Returns:
        Dict with seven keys:

        missing_campaigns
            Names in recommended plan but not found in live.

        extra_campaigns
            Names in live but not in the recommended plan.

        keyword_gaps
            Recommended keywords absent from live ad groups.
            Each entry: {"campaign", "ad_group", "keyword", "match_type"}

        keyword_waste
            Live keywords absent from the recommended plan.
            Same dict format as keyword_gaps.

        ad_copy_diffs
            Headline/description texts that differ between recommended and live.
            Each entry: {"campaign", "ad_group", "type", "recommended", "live"}

        budget_diffs
            Budget mismatches between recommended (float SEK/day) and live.
            Each entry: {"campaign", "recommended_budget", "live_budget"}

        bid_strategy_diffs
            Bid strategy mismatches.
            Each entry: {"campaign", "recommended", "live"}
    """
    # Build name-keyed maps (case-insensitive)
    live_by_name: dict[str, dict] = {c["name"].lower(): c for c in live_campaigns}
    rec_by_name: dict[str, object] = {
        c.name.lower(): c for c in recommended_plan.campaigns
    }

    live_names = set(live_by_name.keys())
    rec_names = set(rec_by_name.keys())

    missing_campaigns: list[str] = sorted(
        c.name for c in recommended_plan.campaigns if c.name.lower() not in live_names
    )
    extra_campaigns: list[str] = sorted(
        live_by_name[n]["name"] for n in (live_names - rec_names)
    )

    keyword_gaps: list[dict] = []
    keyword_waste: list[dict] = []
    ad_copy_diffs: list[dict] = []
    budget_diffs: list[dict] = []
    bid_strategy_diffs: list[dict] = []

    matched_names = live_names & rec_names
    for name_lower in matched_names:
        live_camp = live_by_name[name_lower]
        rec_camp = rec_by_name[name_lower]  # type: ignore[assignment]

        # Budget diff
        try:
            live_budget_str = live_camp.get("campaign_budget", "")
            rec_budget = float(rec_camp.budget_sek_daily)  # type: ignore[union-attr]
            budget_diffs.append(
                {
                    "campaign": rec_camp.name,  # type: ignore[union-attr]
                    "recommended_budget": rec_budget,
                    "live_budget": live_budget_str,
                }
            )
        except (TypeError, ValueError, AttributeError):
            pass

        # Bid strategy diff
        rec_bid = getattr(rec_camp, "bid_strategy", None)
        # Live campaigns from the API don't carry bid_strategy in our dict;
        # we keep it graceful — only record when there is something to compare.
        if rec_bid:
            live_bid = live_camp.get("bid_strategy", "")
            if live_bid and rec_bid.upper() != live_bid.upper():
                bid_strategy_diffs.append(
                    {
                        "campaign": rec_camp.name,  # type: ignore[union-attr]
                        "recommended": rec_bid,
                        "live": live_bid,
                    }
                )

        # Per-ad-group keyword and ad copy comparison
        live_ag_by_name: dict[str, dict] = {
            ag["name"].lower(): ag for ag in live_camp.get("ad_groups", [])
        }
        for rec_ag in getattr(rec_camp, "ad_groups", []):
            ag_name_lower = rec_ag.name.lower()
            live_ag = live_ag_by_name.get(ag_name_lower)

            # --- Keyword gaps and waste ---
            rec_kw_set: set[tuple[str, str]] = {
                (kw.text.lower(), kw.match_type.upper())
                for kw in rec_ag.keywords
            }
            if live_ag is not None:
                live_kw_set: set[tuple[str, str]] = {
                    (kw["text"].lower(), kw["match_type"].upper())
                    for kw in live_ag.get("keywords", [])
                }
            else:
                live_kw_set = set()

            # Recommended keywords not live → gaps
            for text, match_type in sorted(rec_kw_set - live_kw_set):
                keyword_gaps.append(
                    {
                        "campaign": rec_camp.name,  # type: ignore[union-attr]
                        "ad_group": rec_ag.name,
                        "keyword": text,
                        "match_type": match_type,
                    }
                )

            # Live keywords not recommended → waste
            for text, match_type in sorted(live_kw_set - rec_kw_set):
                keyword_waste.append(
                    {
                        "campaign": live_camp["name"],
                        "ad_group": live_ag["name"] if live_ag else rec_ag.name,
                        "keyword": text,
                        "match_type": match_type,
                    }
                )

            # --- Ad copy diffs ---
            rec_headlines: set[str] = {
                h.text.lower() for ad in rec_ag.ads for h in ad.headlines
            }
            rec_descriptions: set[str] = {
                d.text.lower() for ad in rec_ag.ads for d in ad.descriptions
            }

            live_headlines: set[str] = set()
            live_descriptions: set[str] = set()
            if live_ag is not None:
                for live_ad in live_ag.get("ads", []):
                    live_headlines.update(h.lower() for h in live_ad.get("headlines", []))
                    live_descriptions.update(
                        d.lower() for d in live_ad.get("descriptions", [])
                    )

            for hl in sorted(rec_headlines - live_headlines):
                ad_copy_diffs.append(
                    {
                        "campaign": rec_camp.name,  # type: ignore[union-attr]
                        "ad_group": rec_ag.name,
                        "type": "headline",
                        "recommended": hl,
                        "live": None,
                    }
                )

            for desc in sorted(rec_descriptions - live_descriptions):
                ad_copy_diffs.append(
                    {
                        "campaign": rec_camp.name,  # type: ignore[union-attr]
                        "ad_group": rec_ag.name,
                        "type": "description",
                        "recommended": desc,
                        "live": None,
                    }
                )

    return {
        "missing_campaigns": missing_campaigns,
        "extra_campaigns": extra_campaigns,
        "keyword_gaps": keyword_gaps,
        "keyword_waste": keyword_waste,
        "ad_copy_diffs": ad_copy_diffs,
        "budget_diffs": budget_diffs,
        "bid_strategy_diffs": bid_strategy_diffs,
    }


def format_audit_report(diff: dict, client_name: str) -> str:
    """Render a structured diff dict as a Swedish-language markdown audit report.

    Args:
        diff: Output of compare().
        client_name: Human-readable client name used in the report title.

    Returns:
        Full markdown string ready to write to disk.
    """
    today = datetime.now().strftime("%Y-%m-%d")

    missing = diff.get("missing_campaigns", [])
    extra = diff.get("extra_campaigns", [])
    keyword_gaps = diff.get("keyword_gaps", [])
    keyword_waste = diff.get("keyword_waste", [])
    ad_copy_diffs = diff.get("ad_copy_diffs", [])
    budget_diffs = diff.get("budget_diffs", [])
    bid_diffs = diff.get("bid_strategy_diffs", [])

    lines: list[str] = [
        f"# Kampanjgranskning: {client_name}",
        "",
        f"**Datum:** {today}",
        "",
        "---",
        "",
        "## Sammanfattning",
        "",
        f"| Kategori | Antal |",
        f"|----------|-------|",
        f"| Saknade kampanjer | {len(missing)} |",
        f"| Extra kampanjer (ej i plan) | {len(extra)} |",
        f"| Saknade sökord | {len(keyword_gaps)} |",
        f"| Potentiellt sökordssloseri | {len(keyword_waste)} |",
        f"| Annonskopieringsskillnader | {len(ad_copy_diffs)} |",
        f"| Budgetskillnader | {len(budget_diffs)} |",
        f"| Budstrategiskillnader | {len(bid_diffs)} |",
        "",
        "---",
        "",
    ]

    # Missing campaigns
    lines += ["## Saknade kampanjer", ""]
    if missing:
        lines += ["| Kampanjnamn |", "|-------------|"]
        for name in missing:
            lines.append(f"| {name} |")
    else:
        lines.append("*Inga saknade kampanjer.*")
    lines.append("")

    # Extra campaigns
    lines += ["## Extra kampanjer (ej i plan)", ""]
    if extra:
        lines += ["| Kampanjnamn |", "|-------------|"]
        for name in extra:
            lines.append(f"| {name} |")
    else:
        lines.append("*Inga extra kampanjer.*")
    lines.append("")

    # Keyword gaps
    lines += ["## Sokordsluckor", ""]
    if keyword_gaps:
        lines += [
            "| Kampanj | Annonsgrupp | Sökord | Matchningstyp |",
            "|---------|-------------|--------|---------------|",
        ]
        for item in keyword_gaps:
            lines.append(
                f"| {item['campaign']} | {item['ad_group']} "
                f"| {item['keyword']} | {item['match_type']} |"
            )
    else:
        lines.append("*Inga sökordsluckor.*")
    lines.append("")

    # Keyword waste
    lines += ["## Potentiellt sokordsslöseri", ""]
    if keyword_waste:
        lines += [
            "| Kampanj | Annonsgrupp | Sökord | Matchningstyp |",
            "|---------|-------------|--------|---------------|",
        ]
        for item in keyword_waste:
            lines.append(
                f"| {item['campaign']} | {item['ad_group']} "
                f"| {item['keyword']} | {item['match_type']} |"
            )
    else:
        lines.append("*Inga potentiella sokordssloserier.*")
    lines.append("")

    # Ad copy diffs
    lines += ["## Annonskopieringsskillnader", ""]
    if ad_copy_diffs:
        lines += [
            "| Kampanj | Annonsgrupp | Typ | Rekommenderat | Live |",
            "|---------|-------------|-----|---------------|------|",
        ]
        for item in ad_copy_diffs:
            live_val = item["live"] or "*(saknas)*"
            lines.append(
                f"| {item['campaign']} | {item['ad_group']} "
                f"| {item['type']} | {item['recommended']} | {live_val} |"
            )
    else:
        lines.append("*Inga annonskopieringsskillnader.*")
    lines.append("")

    # Budget diffs
    lines += ["## Budgetskillnader", ""]
    if budget_diffs:
        lines += [
            "| Kampanj | Rekommenderad budget (SEK/dag) | Live budget |",
            "|---------|-------------------------------|-------------|",
        ]
        for item in budget_diffs:
            lines.append(
                f"| {item['campaign']} | {item['recommended_budget']:.2f} "
                f"| {item['live_budget']} |"
            )
    else:
        lines.append("*Inga budgetskillnader.*")
    lines.append("")

    # Bid strategy diffs
    lines += ["## Budstrategiskillnader", ""]
    if bid_diffs:
        lines += [
            "| Kampanj | Rekommenderad | Live |",
            "|---------|---------------|------|",
        ]
        for item in bid_diffs:
            lines.append(
                f"| {item['campaign']} | {item['recommended']} | {item['live']} |"
            )
    else:
        lines.append("*Inga budstrategiskillnader.*")
    lines.append("")

    lines += [
        "---",
        "",
        f"*Rapport genererad av SEM Master — {today}*",
        "",
    ]

    return "\n".join(lines)
